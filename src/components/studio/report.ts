const BRAND = "#a3341f";

const title = (text: string, subtitle?: string) => ({
  title: {
    enabled: true,
    text,
  },
  ...(subtitle
    ? { subtitle: { enabled: true, text: subtitle } }
    : {}),
});

const kpi = (text: string) => ({
  ...title(text),
  style: {
    typography: {
      fontSize: 34,
      fontWeight: "bold" as const,
    },
    color: BRAND,
    verticalAlign: "center" as const,
  },
});

const at = (
  xTrack: number,
  yTrack: number,
  xSpan: number,
  ySpan: number,
) => ({ xTrack, yTrack, xSpan, ySpan });

/* =========================================
   INITIAL DASHBOARD
========================================= */

export function initialReport(
  lang: Lang,
  showInventory = true,
  showReservations = true,
): AgReportState {
  const l = L[lang];

  const importe = {
    id: "ventas.importe",
    aggregation: "sum" as const,
  };

  const sold = {
    type: "value",
    format: {
      ...kpi(l.kSold),
      style: {
        ...kpi(l.kSold).style,
        sparkline: { type: "bar" },
      },
    },
    dataMapping: {
      value: [importe],
      sparklineX: [{ id: "ventas.horaDelDia" }],
    },
  };

  const sales = {
    type: "value",
    format: kpi(l.kSales),
    dataMapping: {
      value: [
        {
          id: "ventas.venta",
          aggregation: "countd" as const,
        },
      ],
    },
  };

  const dishes = {
    type: "value",
    format: kpi(l.kDishes),
    dataMapping: {
      value: [
        {
          id: "ventas.cantidad",
          aggregation: "sum" as const,
        },
      ],
    },
  };

  const held = {
    type: "value",
    format: kpi(l.kHeld),
    dataMapping: {
      value: [
        {
          id: "apartados.cliente",
          aggregation: "count" as const,
        },
      ],
    },
  };

  const byDish = {
    type: "column-chart-grouped",
    format: title(l.byDish, l.byDishSub),
    dataMapping: {
      categoryKey: [{ id: "ventas.platillo" }],
      valueKey: [importe],
      tooltipKey: [
        {
          id: "ventas.cantidad",
          aggregation: "sum" as const,
        },
      ],
    },
    sort: [{ field: importe, direction: "desc" as const }],
  };

  const ticket = {
    type: "cashup-ticket",
    format: title(l.ticket),
    dataMapping: {
      concepto: [{ id: "ventas.metodo" }],
      importe: [importe],
    },
    sort: [{ field: importe, direction: "desc" as const }],
  };

  const byHour = {
    type: "line-chart",
    format: title(l.byHour),
    dataMapping: {
      categoryKey: [{ id: "ventas.horaDelDia" }],
      valueKey: [importe],
    },
    sort: [
      {
        field: { id: "ventas.horaDelDia" },
        direction: "asc" as const,
      },
    ],
  };

  const byMethod = {
    type: "donut-chart",
    format: title(l.byMethod),
    dataMapping: {
      categoryKey: [{ id: "ventas.metodo" }],
      valueKey: [importe],
    },
  };

  const stock = {
    type: "bar-chart-grouped",
    format: title(l.stock, l.stockSub),
    dataMapping: {
      categoryKey: [{ id: "inventario.ingrediente" }],
      valueKey: [
        {
          id: "inventario.usadoPct",
          aggregation: "sum" as const,
        },
      ],
      tooltipKey: [
        {
          id: "inventario.usado",
          aggregation: "sum" as const,
        },
        {
          id: "inventario.queda",
          aggregation: "sum" as const,
        },
      ],
    },
    sort: [
      {
        field: {
          id: "inventario.usadoPct",
          aggregation: "sum" as const,
        },
        direction: "desc" as const,
      },
    ],
  };

  const detail = {
    type: "grid",
    format: title(l.sales),
    dataMapping: {
      cols: [
        { id: "ventas.hora" },
        { id: "ventas.platillo" },
        { id: "ventas.cantidad" },
        { id: "ventas.importe" },
        { id: "ventas.metodo" },
        { id: "ventas.apartado" },
      ],
    },
    sort: [
      {
        field: { id: "ventas.hora" },
        direction: "desc" as const,
      },
    ],
  };

  // Build a layout without empty inventory or reservation widgets.
  const widgets = {
    sold,
    sales,
    dishes,
    ...(showReservations ? { held } : {}),
    byDish,
    ticket,
    byHour,
    byMethod,
    ...(showInventory ? { stock } : {}),
    detail,
  };

  // The three sales indicators are wide.
  // Reservations are displayed only when data exists.
  const topHeight = showReservations ? 20 : 11;
  const chartsY = topHeight;

  const widgetLayout = {
    sold: at(0, 0, 8, 11),
    sales: at(8, 0, 8, 11),
    dishes: at(16, 0, 8, 11),

    ...(showReservations
      ? { held: at(0, 11, 24, 9) }
      : {}),

    byDish: at(0, chartsY, 15, 24),
    ticket: at(15, chartsY, 9, 24),

    byHour: at(0, chartsY + 24, 15, 24),
    byMethod: at(15, chartsY + 24, 9, 24),

    ...(showInventory
      ? {
          stock: at(0, chartsY + 48, 24, 20),
          detail: at(0, chartsY + 68, 24, 26),
        }
      : {
          detail: at(0, chartsY + 48, 24, 26),
        }),
  };

  return {
    pages: [
      {
        id: "corte",
        widgets,
        widgetLayout,
      },
    ],
    panels: {
      filters: { collapsed: true },
      edit: { collapsed: true },
      data: { collapsed: true },
      ai: { collapsed: true },
    },
    selectedPageId: "corte",
    version: "3.0.0",
  } as unknown as AgReportState;
}

/* =========================================
   FACTS FOR AI ASSISTANT
========================================= */

export function cashUpFacts(t: CashUpTables): string {
  const money = (value: number) =>
    `$${Math.round(value).toLocaleString("en-US")} ${t.currency}`;

  const group = (
    key: "platillo" | "metodo" | "horaDelDia",
  ) => {
    const values = new Map<
      string,
      { importe: number; cantidad: number }
    >();

    for (const row of t.ventas) {
      const current = values.get(row[key]) ?? {
        importe: 0,
        cantidad: 0,
      };

      current.importe += row.importe;
      current.cantidad += row.cantidad;
      values.set(row[key], current);
    }

    return [...values].sort(
      (a, b) => b[1].importe - a[1].importe,
    );
  };

  const total = t.ventas.reduce(
    (sum, row) => sum + row.importe,
    0,
  );

  const sales = new Set(
    t.ventas.map((row) => row.venta),
  ).size;

  const lines = [
    `Total sold: ${money(total)} in ${sales} sales (${t.ventas.reduce(
      (sum, row) => sum + row.cantidad,
      0,
    )} dishes).`,

    `Per dish: ${
      group("platillo")
        .map(
          ([name, value]) =>
            `${name} ${money(value.importe)} (${value.cantidad} sold)`,
        )
        .join("; ") || "none"
    }.`,

    `Per payment method: ${
      group("metodo")
        .map(
          ([name, value]) =>
            `${name} ${money(value.importe)}`,
        )
        .join("; ") || "none"
    }.`,

    `Per hour: ${
      group("horaDelDia")
        .sort((a, b) => a[0].localeCompare(b[0]))
        .map(
          ([hour, value]) =>
            `${hour} ${money(value.importe)}`,
        )
        .join("; ") || "none"
    }.`,

    `Inventory records: ${
      t.inventario.length
        ? [...t.inventario]
            .sort((a, b) => b.usadoPct - a.usadoPct)
            .map(
              (item) =>
                `${item.ingrediente}: ${item.queda} ${item.unidad} left, ${item.usadoPct}% used`,
            )
            .join("; ")
        : "not available for this report"
    }.`,

    `Reservation records: ${
      t.apartados.length
        ? t.apartados
            .map(
              (item) =>
                `${item.cliente}, ${item.estado}, ${money(item.importe)}`,
            )
            .join("; ")
        : "not available for this report"
    }.`,
  ];

  return lines.join("\n").slice(0, 6000);
}
